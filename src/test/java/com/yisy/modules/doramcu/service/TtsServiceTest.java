package com.yisy.modules.doramcu.service;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Nested;
import org.junit.jupiter.api.Test;

import java.time.Instant;
import java.util.*;

import static org.junit.jupiter.api.Assertions.*;

class TtsServiceTest {

    private TtsService service;

    @BeforeEach
    void setUp() {
        service = new TtsService();
    }

    @Nested
    class EventTypeTests {
        @Test
        void allTypes_haveNames() {
            for (TtsService.EventType type : TtsService.EventType.values()) {
                assertNotNull(type.getName());
                assertFalse(type.getName().isEmpty());
            }
        }

        @Test
        void eventType_count() {
            assertEquals(15, TtsService.EventType.values().length);
        }
    }

    @Nested
    class VoiceProfileTests {
        @Test
        void allProfiles_haveNames() {
            for (TtsService.VoiceProfile profile : TtsService.VoiceProfile.values()) {
                assertNotNull(profile.getName());
            }
        }

        @Test
        void voiceProfile_count() {
            assertEquals(5, TtsService.VoiceProfile.values().length);
        }

        @Test
        void narrator_default() {
            assertEquals(0.9, TtsService.VoiceProfile.NARRATOR.getPitch());
            assertEquals(1.0, TtsService.VoiceProfile.NARRATOR.getRate());
        }
    }

    @Nested
    class NarrationModel {
        @Test
        void build_minimal() {
            TtsService.Narration n = TtsService.Narration.builder().build();
            assertNotNull(n.getId());
            assertEquals(8, n.getId().length());
        }

        @Test
        void build_full() {
            Instant ts = Instant.ofEpochSecond(1000);
            TtsService.Narration n = TtsService.Narration.builder()
                    .id("test1234").sessionId("s1")
                    .eventType(TtsService.EventType.COMBAT)
                    .voiceProfile(TtsService.VoiceProfile.COMMANDER)
                    .text("Combat!").ssml("<speak>Combat!</speak>")
                    .metadata(Map.of("k", "v")).timestamp(ts).build();
            assertEquals("test1234", n.getId());
            assertEquals("s1", n.getSessionId());
            assertEquals(TtsService.EventType.COMBAT, n.getEventType());
            assertEquals(TtsService.VoiceProfile.COMMANDER, n.getVoiceProfile());
            assertEquals("Combat!", n.getText());
            assertEquals("<speak>Combat!</speak>", n.getSsml());
            assertEquals("v", n.getMetadata().get("k"));
            assertEquals(ts, n.getTimestamp());
        }

        @Test
        void ssml_autoGenerated() {
            TtsService.Narration n = TtsService.Narration.builder()
                    .text("Test").voiceProfile(TtsService.VoiceProfile.NARRATOR).build();
            assertTrue(n.getSsml().contains("<speak>"));
            assertTrue(n.getSsml().contains("Test"));
        }

        @Test
        void metadata_immutable() {
            Map<String, Object> data = new HashMap<>();
            data.put("k", "v");
            TtsService.Narration n = TtsService.Narration.builder().metadata(data).build();
            assertThrows(UnsupportedOperationException.class, () -> n.getMetadata().put("x", "y"));
        }
    }

    @Nested
    class SettingsTests {
        @Test
        void builder_defaults() {
            TtsService.NarrationSettings s = TtsService.NarrationSettings.builder("s1").build();
            assertTrue(s.isEnabled());
            assertEquals(TtsService.VoiceProfile.NARRATOR, s.getDefaultVoice());
            assertEquals(15, s.getEnabledEvents().size());
        }

        @Test
        void builder_nullSessionId() {
            assertThrows(IllegalArgumentException.class, () -> TtsService.NarrationSettings.builder(null).build());
        }

        @Test
        void shouldNarrate_enabled() {
            TtsService.NarrationSettings s = TtsService.NarrationSettings.builder("s1").build();
            assertTrue(s.shouldNarrate(TtsService.EventType.COMBAT));
        }

        @Test
        void shouldNarrate_disabled() {
            TtsService.NarrationSettings s = TtsService.NarrationSettings.builder("s1").enabled(false).build();
            assertFalse(s.shouldNarrate(TtsService.EventType.COMBAT));
        }

        @Test
        void shouldNarrate_eventNotEnabled() {
            Set<TtsService.EventType> events = EnumSet.of(TtsService.EventType.COMBAT);
            TtsService.NarrationSettings s = TtsService.NarrationSettings.builder("s1").enabledEvents(events).build();
            assertTrue(s.shouldNarrate(TtsService.EventType.COMBAT));
            assertFalse(s.shouldNarrate(TtsService.EventType.TRADE));
        }
    }

    @Nested
    class SettingsManagement {
        @Test
        void registerSettings() {
            TtsService.NarrationSettings s = TtsService.NarrationSettings.builder("s1")
                    .defaultVoice(TtsService.VoiceProfile.COMMANDER).build();
            service.registerSettings(s);
            assertEquals(TtsService.VoiceProfile.COMMANDER, service.getSettings("s1").getDefaultVoice());
        }

        @Test
        void getSettings_createsDefault() {
            assertTrue(service.getSettings("new").isEnabled());
        }
    }

    @Nested
    class Narrate {
        @Test
        void narrate_basic() {
            Map<String, Object> data = Map.of("player", "Fed", "target", "S7");
            TtsService.Narration n = service.narrate("s1", TtsService.EventType.FLEET_MOVE, data);
            assertNotNull(n);
            assertTrue(n.getText().contains("Fed"));
            assertTrue(n.getText().contains("S7"));
        }

        @Test
        void narrate_disabledEvent() {
            Set<TtsService.EventType> events = EnumSet.of(TtsService.EventType.COMBAT);
            service.registerSettings(TtsService.NarrationSettings.builder("s1").enabledEvents(events).build());
            assertNull(service.narrate("s1", TtsService.EventType.FLEET_MOVE, Collections.emptyMap()));
        }

        @Test
        void narrate_disabled() {
            service.registerSettings(TtsService.NarrationSettings.builder("s1").enabled(false).build());
            assertNull(service.narrate("s1", TtsService.EventType.COMBAT, Collections.emptyMap()));
        }

        @Test
        void narrate_customVoice() {
            service.registerSettings(TtsService.NarrationSettings.builder("s1")
                    .defaultVoice(TtsService.VoiceProfile.COMMANDER).build());
            TtsService.Narration n = service.narrate("s1", TtsService.EventType.COMBAT, Map.of("player", "Klingon"));
            assertEquals(TtsService.VoiceProfile.COMMANDER, n.getVoiceProfile());
        }

        @Test
        void narrate_storesInHistory() {
            service.narrate("s1", TtsService.EventType.COMBAT, Map.of("player", "A"));
            assertEquals(1, service.getHistory("s1").size());
        }

        @Test
        void narrate_trimsHistory() {
            for (int i = 0; i < 110; i++) {
                service.narrate("s1", TtsService.EventType.FLEET_MOVE, Map.of("count", String.valueOf(i)));
            }
            assertEquals(100, service.getHistory("s1").size());
        }
    }

    @Nested
    class NarrationText {
        @Test
        void fleetMove() {
            String text = service.generateNarrationText(TtsService.EventType.FLEET_MOVE,
                    Map.of("player", "Fed", "subject", "fleet", "target", "S7"));
            assertEquals("Fed has moved fleet to S7.", text);
        }

        @Test
        void combat() {
            String text = service.generateNarrationText(TtsService.EventType.COMBAT,
                    Map.of("player", "Klingon", "target", "Fed", "count", "5"));
            assertEquals("Combat! Klingon engages Fed. 5 vessels involved.", text);
        }

        @Test
        void victory() {
            String text = service.generateNarrationText(TtsService.EventType.VICTORY,
                    Map.of("player", "Fed", "target", "Klingon", "detail", "Total!"));
            assertEquals("Victory! Fed defeats Klingon! Total!", text);
        }

        @Test
        void playerJoin() {
            String text = service.generateNarrationText(TtsService.EventType.PLAYER_JOIN,
                    Map.of("player", "Picard"));
            assertEquals("Picard joins the game.", text);
        }

        @Test
        void defaults() {
            String text = service.generateNarrationText(TtsService.EventType.FLEET_MOVE, Collections.emptyMap());
            assertEquals("An unknown player has moved the fleet to an unknown location.", text);
        }

        @Test
        void nullData() {
            String text = service.generateNarrationText(TtsService.EventType.FLEET_MOVE, null);
            assertEquals("An unknown player has moved the fleet to an unknown location.", text);
        }
    }

    @Nested
    class SsmlGeneration {
        @Test
        void toSsml_basic() {
            String ssml = TtsService.toSsml("Hello", TtsService.VoiceProfile.NARRATOR);
            assertTrue(ssml.contains("<speak>"));
            assertTrue(ssml.contains("Hello"));
        }

        @Test
        void toSsml_escape() {
            String ssml = TtsService.toSsml("A & B", TtsService.VoiceProfile.NARRATOR);
            assertTrue(ssml.contains("&amp;"));
        }

        @Test
        void toSsml_null() {
            assertEquals("", TtsService.toSsml(null, TtsService.VoiceProfile.NARRATOR));
        }
    }

    @Nested
    class History {
        @Test
        void getHistory_empty() {
            assertTrue(service.getHistory("none").isEmpty());
        }

        @Test
        void getHistory_afterNarrate() {
            service.narrate("s1", TtsService.EventType.COMBAT, Map.of("p", "A"));
            service.narrate("s1", TtsService.EventType.VICTORY, Map.of("p", "B"));
            assertEquals(2, service.getHistory("s1").size());
        }

        @Test
        void getRecent_limited() {
            for (int i = 0; i < 10; i++) service.narrate("s1", TtsService.EventType.FLEET_MOVE, Collections.emptyMap());
            assertEquals(3, service.getRecent("s1", 3).size());
        }

        @Test
        void getHistoryByType() {
            service.narrate("s1", TtsService.EventType.COMBAT, Collections.emptyMap());
            service.narrate("s1", TtsService.EventType.FLEET_MOVE, Collections.emptyMap());
            service.narrate("s1", TtsService.EventType.COMBAT, Collections.emptyMap());
            assertEquals(2, service.getHistoryByType("s1", TtsService.EventType.COMBAT).size());
            assertEquals(1, service.getHistoryByType("s1", TtsService.EventType.FLEET_MOVE).size());
        }
    }

    @Nested
    class Statistics {
        @Test
        void statistics_empty() {
            Map<String, Object> stats = service.getStatistics("empty");
            assertEquals(0, stats.get("totalNarrations"));
        }

        @Test
        void statistics_afterNarrate() {
            service.narrate("s1", TtsService.EventType.COMBAT, Map.of("p", "A"));
            service.narrate("s1", TtsService.EventType.VICTORY, Map.of("p", "B"));
            Map<String, Object> stats = service.getStatistics("s1");
            assertEquals(2, stats.get("totalNarrations"));
        }
    }

    @Nested
    class Clear {
        @Test
        void clearHistory() {
            service.narrate("s1", TtsService.EventType.COMBAT, Collections.emptyMap());
            service.clearHistory("s1");
            assertTrue(service.getHistory("s1").isEmpty());
        }

        @Test
        void clearAll() {
            service.narrate("s1", TtsService.EventType.COMBAT, Collections.emptyMap());
            service.clearAll();
            assertTrue(service.getHistory("s1").isEmpty());
        }
    }

    @Nested
    class Enums {
        @Test
        void allEventTypes() {
            assertEquals(15, service.getAllEventTypes().size());
        }

        @Test
        void allVoiceProfiles() {
            assertEquals(5, service.getAllVoiceProfiles().size());
        }
    }

    @Nested
    class Integration {
        @Test
        void fullWorkflow() {
            Set<TtsService.EventType> events = EnumSet.of(TtsService.EventType.COMBAT, TtsService.EventType.VICTORY, TtsService.EventType.FLEET_MOVE);
            service.registerSettings(TtsService.NarrationSettings.builder("g1")
                    .defaultVoice(TtsService.VoiceProfile.COMMANDER).enabledEvents(events).volume(0.8).build());

            assertNotNull(service.narrate("g1", TtsService.EventType.FLEET_MOVE, Map.of("player", "Fed", "target", "S7")));
            assertNotNull(service.narrate("g1", TtsService.EventType.COMBAT, Map.of("player", "Fed", "target", "Klingon")));
            assertNull(service.narrate("g1", TtsService.EventType.TRADE, Map.of("player", "Fed")));
            assertEquals(2, service.getHistory("g1").size());
        }
    }
}
