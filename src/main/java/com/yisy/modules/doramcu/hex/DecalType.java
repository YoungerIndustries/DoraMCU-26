package com.yisy.modules.doramcu.hex;

/**
 * Enumerates the types of decals that can be placed on a skin.
 */
public enum DecalType {
    /**
     * Text decals for call signs, unit IDs, registration numbers, etc.
     */
    TEXT,

    /**
     * Symbol decals for insignias, emblems, logos, and icons.
     */
    SYMBOL,

    /**
     * Faction emblem decals that represent faction affiliation.
     */
    FACTION_EMBLEM
}
