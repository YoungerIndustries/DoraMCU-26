import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import java.util.*;
import java.util.stream.Collectors;

/**
 * REST API for accessing planet surface data generated by the Galaxy Overlord.
 * <p>
 * Game clients (Unity, web, etc.) use these endpoints to retrieve the 3D world
 * data for rendering: terrain hexes, settlements, industries, stations, vehicles,
 * and interior dungeon rooms for exploration.
 * </p>
 * <p>
 * All endpoints at /api/v1/planets
 * </p>
 */
@RestController
@RequestMapping("/api/v1/planets")
public class HexPlanetSurfaceController {

    private static final Logger log = LoggerFactory.getLogger(HexPlanetSurfaceController.class);

    private final DefaultPlanetSurfaceBuilder planetSurfaceBuilder;
    private final PlanetSurfacePersistenceService persistenceService;

    public HexPlanetSurfaceController(
            DefaultPlanetSurfaceBuilder planetSurfaceBuilder,
            PlanetSurfacePersistenceService persistenceService) {
        this.planetSurfaceBuilder = planetSurfaceBuilder;
        this.persistenceService = persistenceService;
    }

    /**
     * Get the full surface data for a planet.
     * <p>
     * Returns terrain hexes, settlements, industries, stations, and vehicles.
     * If the planet is not in memory, loads it from the database first.
     * </p>
     *
     * @param planetId the planet ID
     * @return the full planet surface data
     */
    @GetMapping("/{planetId}/surface")
    @org.springframework.transaction.annotation.Transactional(readOnly = true)
    public ResponseEntity<PlanetSurfaceDto> getPlanetSurface(@PathVariable int planetId) {
        log.info("GET /api/v1/planets/{}/surface", planetId);

        Planet planet = new Planet(planetId);
        PlanetSurfaceDto dto = buildPlanetSurfaceDto(planet);

        if (dto.getTerrainHexes() == null || dto.getTerrainHexes().isEmpty()) {
            return ResponseEntity.notFound().build();
        }

        return ResponseEntity.ok(dto);
    }


    /**
     * Get the summary of a planet's surface data.
     *
     * @param planetId the planet ID
     * @return summary counts of each object type
     */
    @GetMapping("/{planetId}/summary")
    @org.springframework.transaction.annotation.Transactional(readOnly = true)
    public ResponseEntity<Map<String, Long>> getPlanetSummary(@PathVariable int planetId) {
        log.info("GET /api/v1/planets/{}/summary", planetId);

        if (!persistenceService.hasPlanetData(planetId)) {
            return ResponseEntity.notFound().build();
        }

        Map<String, Long> summary = persistenceService.getPlanetSummary(planetId);
        return ResponseEntity.ok(summary);
    }

    /**
     * Trigger generation of a new planet surface.
     * <p>
     * If the planet already exists in the database, returns the existing data.
     * Otherwise, generates the surface procedurally and saves it.
     * </p>
     *
     * @param planetId the planet ID
     * @return the generated planet surface data
     */
    @PostMapping("/{planetId}/generate")
    public ResponseEntity<PlanetSurfaceDto> generatePlanet(@PathVariable int planetId) {
        log.info("POST /api/v1/planets/{}/generate", planetId);

        Planet planet = new Planet(planetId);
        planet.setName("Planet-" + planetId);

        // Check if already exists
        if (persistenceService.hasPlanetData(planetId)) {
            log.info("Planet {} already exists, loading from database", planetId);
            persistenceService.loadPlanetSurface(planet, planetSurfaceBuilder);
            PlanetSurfaceDto dto = buildPlanetSurfaceDto(planet);
            return ResponseEntity.ok(dto);
        }

        // Generate new planet
        long seed = planetId * 31L;
        int hexCount = planetSurfaceBuilder.generateBiomes(planet, seed);
        log.info("Planet {} surface generated: {} hex cells", planetId, hexCount);

        // Auto-populate
        Map<String, Integer> populateSummary = planetSurfaceBuilder.autoPopulatePlanet(planet, seed, "overlord");
        log.info("Planet {} auto-populated: {}", planetId, populateSummary);

        // Save to database
        persistenceService.savePlanetSurface(planet, planetSurfaceBuilder);

        PlanetSurfaceDto dto = buildPlanetSurfaceDto(planet);
        return ResponseEntity.ok(dto);
    }

    // ---- DTO Mapping Methods ----

    private PlanetSurfaceDto buildPlanetSurfaceDto(Planet planet) {
        PlanetSurfaceDto dto = new PlanetSurfaceDto(planet.getId(), planet.getName());

        // Terrain hexes - parse from terrainMap keys (format: "x,y,z")
        Map<String, TerrainData> terrainData = planetSurfaceBuilder.getAllTerrainData();
        List<TerrainHexDto> terrainHexes = new ArrayList<>();
        for (Map.Entry<String, TerrainData> entry : terrainData.entrySet()) {
            terrainHexes.add(HexPlanetDtoMapper.toTerrainHexDto(entry.getKey(), entry.getValue()));
        }
        dto.setTerrainHexes(terrainHexes);

        // Settlements
        List<Settlement> settlements = planetSurfaceBuilder.getAllSettlements(planet);
        List<SettlementDto> settlementDtos = settlements.stream()
                .map(HexPlanetDtoMapper::toSettlementDto)
                .collect(Collectors.toList());
        dto.setSettlements(settlementDtos);

        // Industries
        List<Industry> industries = planetSurfaceBuilder.getAllIndustries(planet);
        List<IndustryDto> industryDtos = industries.stream()
                .map(HexPlanetDtoMapper::toIndustryDto)
                .collect(Collectors.toList());
        dto.setIndustries(industryDtos);

        // Stations
        List<Station> stations = planetSurfaceBuilder.getAllStations(planet);
        List<StationDto> stationDtos = stations.stream()
                .map(HexPlanetDtoMapper::toStationDto)
                .collect(Collectors.toList());
        dto.setStations(stationDtos);

        // Vehicles
        List<SurfaceVehicle> vehicles = planetSurfaceBuilder.getAllVehicles(planet);
        List<VehicleDto> vehicleDtos = vehicles.stream()
                .map(HexPlanetDtoMapper::toVehicleDto)
                .collect(Collectors.toList());
        dto.setVehicles(vehicleDtos);

        // Corporations
        List<TransportCorporation> corporations = planetSurfaceBuilder.getAllCorporations(planet);
        List<CorporationDto> corporationDtos = corporations.stream()
                .map(HexPlanetDtoMapper::toCorporationDto)
                .collect(Collectors.toList());
        dto.setCorporations(corporationDtos);

        // Contracts
        List<DeliveryContract> contracts = planetSurfaceBuilder.getAllContracts(planet);
        List<ContractDto> contractDtos = contracts.stream()
                .map(HexPlanetDtoMapper::toContractDto)
                .collect(Collectors.toList());
        dto.setContracts(contractDtos);

        // Quests
        List<PlanetQuest> quests = planetSurfaceBuilder.getAllQuests(planet);
        List<QuestDto> questDtos = quests.stream()
                .map(HexPlanetDtoMapper::toQuestDto)
                .collect(Collectors.toList());
        dto.setQuests(questDtos);

        // Trade Routes
        List<CampaignTradeRoute> tradeRoutes = planetSurfaceBuilder.getAllTradeRoutes(planet);
        List<TradeRouteDto> tradeRouteDtos = tradeRoutes.stream()
                .map(HexPlanetDtoMapper::toTradeRouteDto)
                .collect(Collectors.toList());
        dto.setTradeRoutes(tradeRouteDtos);

        // Summary
        PlanetSurfaceDto.SummaryDto summary = new PlanetSurfaceDto.SummaryDto();
        summary.setTerrainCells(terrainHexes.size());
        summary.setSettlements(settlementDtos.size());
        summary.setIndustries(industryDtos.size());
        summary.setStations(stationDtos.size());
        summary.setVehicles(vehicleDtos.size());
        summary.setCorporations(corporationDtos.size());
        summary.setContracts(contractDtos.size());
        summary.setQuests(questDtos.size());
        summary.setTradeRoutes(tradeRouteDtos.size());

        // Count interiors
        long interiors = 0;
        for (Settlement s : settlements) {
            if (s.getDungeonIds() != null) interiors += s.getDungeonIds().size();
        }
        for (Industry i : industries) {
            if (i.getDungeonId() != null) interiors++;
        }
        for (Station s : stations) {
            if (s.getDungeonId() != null) interiors++;
        }
        summary.setInteriors(interiors);
        dto.setSummary(summary);

        return dto;
    }

}
