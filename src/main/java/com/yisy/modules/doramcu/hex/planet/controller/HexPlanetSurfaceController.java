    private PlanetSurfaceDto buildPlanetSurfaceDto(Planet planet) {
        PlanetSurfaceDto dto = new PlanetSurfaceDto(planet.getId(), planet.getName());

        // Terrain hexes - parse from terrainMap keys (format: "x,y,z")
        Map<String, TerrainData> terrainData = planetSurfaceBuilder.getAllTerrainData();
        List<TerrainHexDto> terrainHexes = new ArrayList<>();
        for (Map.Entry<String, TerrainData> entry : terrainData.entrySet()) {
            terrainHexes.add(toTerrainHexDto(entry.getKey(), entry.getValue()));
        }
        dto.setTerrainHexes(terrainHexes);

        // Settlements
        List<Settlement> settlements = planetSurfaceBuilder.getAllSettlements(planet);
        List<SettlementDto> settlementDtos = settlements.stream()
                .map(this::toSettlementDto)
                .collect(Collectors.toList());
        dto.setSettlements(settlementDtos);

        // Industries
        List<Industry> industries = planetSurfaceBuilder.getAllIndustries(planet);
        List<IndustryDto> industryDtos = industries.stream()
                .map(this::toIndustryDto)
                .collect(Collectors.toList());
        dto.setIndustries(industryDtos);

        // Stations
        List<Station> stations = planetSurfaceBuilder.getAllStations(planet);
        List<StationDto> stationDtos = stations.stream()
                .map(this::toStationDto)
                .collect(Collectors.toList());
        dto.setStations(stationDtos);

        // Vehicles
        List<SurfaceVehicle> vehicles = planetSurfaceBuilder.getAllVehicles(planet);
        List<VehicleDto> vehicleDtos = vehicles.stream()
                .map(this::toVehicleDto)
                .collect(Collectors.toList());
        dto.setVehicles(vehicleDtos);

        // Corporations
        List<TransportCorporation> corporations = planetSurfaceBuilder.getAllCorporations(planet);
        List<CorporationDto> corporationDtos = corporations.stream()
                .map(this::toCorporationDto)
                .collect(Collectors.toList());
        dto.setCorporations(corporationDtos);

        // Contracts
        List<DeliveryContract> contracts = planetSurfaceBuilder.getAllContracts(planet);
        List<ContractDto> contractDtos = contracts.stream()
                .map(this::toContractDto)
                .collect(Collectors.toList());
        dto.setContracts(contractDtos);

        // Quests
        List<PlanetQuest> quests = planetSurfaceBuilder.getAllQuests(planet);
        List<QuestDto> questDtos = quests.stream()
                .map(this::toQuestDto)
                .collect(Collectors.toList());
        dto.setQuests(questDtos);

        // Trade Routes
        List<CampaignTradeRoute> tradeRoutes = planetSurfaceBuilder.getAllTradeRoutes(planet);
        List<TradeRouteDto> tradeRouteDtos = tradeRoutes.stream()
                .map(this::toTradeRouteDto)
                .collect(Collectors.toList());
        dto.setTradeRoutes(tradeRouteDtos);

        // Summary
        PlanetSurfaceDto.SummaryDto summary = new PlanetSurfaceDto.SummaryDto();
        summary.setTerrainCells(terrainHexes.size());
        summary.setSettlements(settlementDtos.size());
        summary.setIndustries(industryDtos.size());
        summary.setStations(stationDtos.size());
        summary.setVehicles(vehicleDtos.size());
        summary.setCorporations(corporationDtos.size());
        summary.setContracts(contractDtos.size());
        summary.setQuests(questDtos.size());
        summary.setTradeRoutes(tradeRouteDtos.size());

        // Count interiors
        long interiors = 0;
        for (Settlement s : settlements) {
            if (s.getDungeonIds() != null) interiors += s.getDungeonIds().size();
        }
        for (Industry i : industries) {
            if (i.getDungeonId() != null) interiors++;
        }
        for (Station s : stations) {
            if (s.getDungeonId() != null) interiors++;
        }
        summary.setInteriors(interiors);
        dto.setSummary(summary);

        return dto;
    }

    private TerrainHexDto toTerrainHexDto(String hexKey, TerrainData td) {
        TerrainHexDto dto = new TerrainHexDto();
        // Parse hex key "x,y,z"
        String[] parts = hexKey.split(",");
        if (parts.length == 3) {
            dto.setX(Integer.parseInt(parts[0].trim()));
            dto.setY(Integer.parseInt(parts[1].trim()));
            dto.setZ(Integer.parseInt(parts[2].trim()));
        }
        dto.setTerrainType(td.getTerrainType() != null ? td.getTerrainType().name() : null);
        dto.setBiome(td.getBiome() != null ? td.getBiome().getName() : null);
        dto.setTemperature(td.getBiome().getTemperature());
        dto.setMoisture(td.getBiome().getMoisture());
        dto.setAltitude(td.getBiome().getAltitude());
        dto.setInfrastructure(td.getInfrastructure() != null ? td.getInfrastructure().name() : null);
        dto.setSettlementId(td.getSettlementId());
        dto.setIndustryId(td.getIndustryId());
        dto.setWater(!td.getTerrainType().isLand());
        return dto;
    }

    private SettlementDto toSettlementDto(Settlement s) {
        SettlementDto dto = new SettlementDto();
        dto.setId(s.getId());
        dto.setName(s.getName());
        Hex3D center = s.getCenterHex();
        if (center != null) {
            dto.setCenterX(center.getX());
            dto.setCenterY(center.getY());
            dto.setCenterZ(center.getZ());
        }
        dto.setSize(s.getSize() != null ? s.getSize().name() : null);
        dto.setPopulation(s.getPopulation());
        dto.setPassengerProduction(s.getPassengerProduction());
        dto.setActive(s.isActive());
        dto.setOwnerEmpireId(s.getOwnerEmpireId());
        dto.setDungeonIds(s.getDungeonIds());
        dto.setHexes(s.getOccupiedHexes() != null ?
                s.getOccupiedHexes().stream().map(h -> h.getX() + "," + h.getY() + "," + h.getZ()).collect(Collectors.toList()) :
                Collections.emptyList());
        return dto;
    }

    private IndustryDto toIndustryDto(Industry i) {
        IndustryDto dto = new IndustryDto();
        dto.setId(i.getId());
        dto.setType(i.getType() != null ? i.getType().name() : null);
        Hex3D pos = i.getLocation();
        if (pos != null) {
            dto.setX(pos.getX());
            dto.setY(pos.getY());
            dto.setZ(pos.getZ());
        }
        dto.setProductionRate((int) (i.getProductionLevel() * 100));
        Map<String, Integer> combinedInventory = new HashMap<>();
        if (i.getInputInventory() != null) {
            i.getInputInventory().forEach((k, v) -> combinedInventory.put("input_" + k.name(), v));
        }
        if (i.getOutputInventory() != null) {
            i.getOutputInventory().forEach((k, v) -> combinedInventory.put("output_" + k.name(), v));
        }
        dto.setInventory(combinedInventory);
        dto.setActive(i.isActive());
        dto.setOwnerEmpireId(i.getOwnerEmpireId());
        dto.setDungeonId(i.getDungeonId());
        return dto;
    }

