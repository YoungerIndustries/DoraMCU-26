package com.yisy.modules.doramcu.earth2026.dto;

import com.yisy.modules.doramcu.earth2026.model.Earth2026Country;
import com.yisy.modules.doramcu.earth2026.model.Earth2026Planet;
import com.yisy.modules.doramcu.earth2026.model.Earth2026Region;
import com.yisy.modules.doramcu.eve.model.AiCharacter;

import java.util.List;
import java.util.Map;

/**
 * Response from Earth 2026 after populating a planet with game-provided character data.
 * <p>
 * This object contains the fully populated {@link Earth2026Planet} with all
 * countries, regions, and AI character assignments. It also includes metadata
 * about which characters were reused from the game's data and which were newly
 * generated by Earth 2026.
 * </p>
 * <p>
 * The requesting game can use this response to:
 * </p>
 * <ul>
 *   <li>Get the complete planet structure with AI-controlled leadership</li>
 *   <li>Know which AI characters were reused vs. newly created</li>
 *   <li>Access the mapping between game character IDs and Earth 2026 AI character IDs</li>
 *   <li>Retrieve any newly generated AI characters that need to be synced back to the game</li>
 * </ul>
 */
public class PlanetPopulationResponse {

    /**
     * The fully populated planet object.
     */
    private Earth2026Planet planet;

    /**
     * All countries on the planet with their AI leaders assigned.
     */
    private List<Earth2026Country> countries;

    /**
     * All regions on the planet with their AI governors assigned.
     */
    private List<Earth2026Region> regions;

    /**
     * AI characters that were reused from the game's existing data.
     * Key = game character ID, Value = Earth 2026 AI character ID.
     */
    private Map<String, Long> reusedAiCharacterIds;

    /**
     * Newly generated AI characters that did not exist in the game's data.
     * These need to be synced back to the requesting game.
     */
    private List<AiCharacter> newAiCharacters;

    /**
     * Player characters from the game that were registered on the planet.
     * Key = game character ID, Value = character name.
     */
    private Map<String, String> registeredPlayerCharacters;

    /**
     * Summary statistics of the population operation.
     */
    private PopulationSummary summary;

    /**
     * Summary of the planet population operation.
     */
    public static class PopulationSummary {
        /**
         * Total characters provided by the game.
         */
        private int totalGameCharacters;

        /**
         * Number of player characters registered.
         */
        private int playerCharactersRegistered;

        /**
         * Number of existing AI characters reused.
         */
        private int aiCharactersReused;

        /**
         * Number of new AI characters generated.
         */
        private int newAiCharactersGenerated;

        /**
         * Number of countries with AI leaders assigned.
         */
        private int countriesWithLeaders;

        /**
         * Number of regions with AI governors assigned.
         */
        private int regionsWithGovernors;

        /**
         * Whether the planet was found or newly created.
         */
        private boolean planetFound;

        public int getTotalGameCharacters() {
            return totalGameCharacters;
        }

        public void setTotalGameCharacters(int totalGameCharacters) {
            this.totalGameCharacters = totalGameCharacters;
        }

        public int getPlayerCharactersRegistered() {
            return playerCharactersRegistered;
        }

        public void setPlayerCharactersRegistered(int playerCharactersRegistered) {
            this.playerCharactersRegistered = playerCharactersRegistered;
        }

        public int getAiCharactersReused() {
            return aiCharactersReused;
        }

        public void setAiCharactersReused(int aiCharactersReused) {
            this.aiCharactersReused = aiCharactersReused;
        }

        public int getNewAiCharactersGenerated() {
            return newAiCharactersGenerated;
        }

        public void setNewAiCharactersGenerated(int newAiCharactersGenerated) {
            this.newAiCharactersGenerated = newAiCharactersGenerated;
        }

        public int getCountriesWithLeaders() {
            return countriesWithLeaders;
        }

        public void setCountriesWithLeaders(int countriesWithLeaders) {
            this.countriesWithLeaders = countriesWithLeaders;
        }

        public int getRegionsWithGovernors() {
            return regionsWithGovernors;
        }

        public void setRegionsWithGovernors(int regionsWithGovernors) {
            this.regionsWithGovernors = regionsWithGovernors;
        }

        public boolean isPlanetFound() {
            return planetFound;
        }

        public void setPlanetFound(boolean planetFound) {
            this.planetFound = planetFound;
        }

        @Override
        public String toString() {
            return "PopulationSummary{" +
                    "totalGameChars=" + totalGameCharacters +
                    ", players=" + playerCharactersRegistered +
                    ", aiReused=" + aiCharactersReused +
                    ", aiNew=" + newAiCharactersGenerated +
                    ", countries=" + countriesWithLeaders +
                    ", regions=" + regionsWithGovernors +
                    ", planetFound=" + planetFound +
                    '}';
        }
    }

    public PlanetPopulationResponse() {
    }

    public Earth2026Planet getPlanet() {
        return planet;
    }

    public void setPlanet(Earth2026Planet planet) {
        this.planet = planet;
    }

    public List<Earth2026Country> getCountries() {
        return countries;
    }

    public void setCountries(List<Earth2026Country> countries) {
        this.countries = countries;
    }

    public List<Earth2026Region> getRegions() {
        return regions;
    }

    public void setRegions(List<Earth2026Region> regions) {
        this.regions = regions;
    }

    public Map<String, Long> getReusedAiCharacterIds() {
        return reusedAiCharacterIds;
    }

    public void setReusedAiCharacterIds(Map<String, Long> reusedAiCharacterIds) {
        this.reusedAiCharacterIds = reusedAiCharacterIds;
    }

    public List<AiCharacter> getNewAiCharacters() {
        return newAiCharacters;
    }

    public void setNewAiCharacters(List<AiCharacter> newAiCharacters) {
        this.newAiCharacters = newAiCharacters;
    }

    public Map<String, String> getRegisteredPlayerCharacters() {
        return registeredPlayerCharacters;
    }

    public void setRegisteredPlayerCharacters(Map<String, String> registeredPlayerCharacters) {
        this.registeredPlayerCharacters = registeredPlayerCharacters;
    }

    public PopulationSummary getSummary() {
        return summary;
    }

    public void setSummary(PopulationSummary summary) {
        this.summary = summary;
    }

    @Override
    public String toString() {
        return "PlanetPopulationResponse{" +
                "planet=" + (planet != null ? planet.getName() : "null") +
                ", countries=" + (countries != null ? countries.size() : 0) +
                ", regions=" + (regions != null ? regions.size() : 0) +
                ", reusedAi=" + (reusedAiCharacterIds != null ? reusedAiCharacterIds.size() : 0) +
                ", newAi=" + (newAiCharacters != null ? newAiCharacters.size() : 0) +
                ", players=" + (registeredPlayerCharacters != null ? registeredPlayerCharacters.size() : 0) +
                ", summary=" + summary +
                '}';
    }
}
