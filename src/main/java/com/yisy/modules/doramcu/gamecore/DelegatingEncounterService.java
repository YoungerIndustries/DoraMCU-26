package com.yisy.modules.doramcu.gamecore;
import org.springframework.stereotype.Service;

import org.springframework.stereotype.Component;

import java.util.ArrayList;
import java.util.List;
import java.util.Random;

/**
 * Default delegating encounter service that provides basic encounter generation
 * using the registry's available modules.
 */
@Component
public class DelegatingEncounterService implements EncounterService {

    private final GameModuleRegistry gameModuleRegistry;
    private final Random random = new Random();

    public DelegatingEncounterService(GameModuleRegistry gameModuleRegistry) {
        this.gameModuleRegistry = gameModuleRegistry;
    }

    @Override
    public List<Encounter> listEncounters() {
        EncounterService delegate = findDelegate();
        if (delegate != null) return delegate.listEncounters();
        List<Encounter> encounters = new ArrayList<>();
        Encounter e = new Encounter();
        e.setId(1L);
        e.setName("Generic Encounter");
        e.setDescription("A basic encounter generated by the delegating service.");
        e.setDifficulty("Medium");
        e.setEncounterType("Generic");
        encounters.add(e);
        return encounters;
    }

    @Override
    public Encounter getEncounter(Long encounterId) {
        EncounterService delegate = findDelegate();
        if (delegate != null) return delegate.getEncounter(encounterId);
        return listEncounters().stream()
                .filter(e -> e.getId().equals(encounterId))
                .findFirst()
                .orElse(null);
    }

    @Override
    public Encounter generateRandomEncounter(String areaId, int level) {
        EncounterService delegate = findDelegate();
        if (delegate != null) return delegate.generateRandomEncounter(areaId, level);
        List<Encounter> encounters = listEncounters();
        if (encounters.isEmpty()) return null;
        Encounter e = encounters.get(random.nextInt(encounters.size()));
        e.setAreaId(areaId);
        return e;
    }

    @Override
    public EncounterResult resolveEncounter(Long encounterId, List<Long> characterIds) {
        EncounterService delegate = findDelegate();
        if (delegate != null) return delegate.resolveEncounter(encounterId, characterIds);
        return new EncounterResult(encounterId, "Generic Encounter", true,
                "Encounter resolved by delegating service", 50);
    }

    private EncounterService findDelegate() {
        return gameModuleRegistry.getAllModules().stream()
                .filter(m -> m.isEnabled() && m.getEncounterService() != null)
                .map(GameModule::getEncounterService)
                .findFirst()
                .orElse(null);
    }
}
