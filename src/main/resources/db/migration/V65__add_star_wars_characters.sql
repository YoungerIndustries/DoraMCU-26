-- V65: Create lore_characters table and seed with Star Wars characters
-- This table stores detailed character data for game lores, linked to game_lores via lore_id.

CREATE TABLE IF NOT EXISTS lore_characters (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,

    -- Link to game_lores
    lore_id BIGINT NOT NULL,
    FOREIGN KEY (lore_id) REFERENCES game_lores(id) ON DELETE CASCADE,

    -- Core identity
    name VARCHAR(255) NOT NULL,
    slug VARCHAR(255) NOT NULL,
    aliases TEXT,

    -- Description
    short_description VARCHAR(500),
    description TEXT,

    -- Classification
    species VARCHAR(100),
    gender VARCHAR(50),
    role VARCHAR(100),
    character_type VARCHAR(100),

    -- Affiliations
    primary_affiliation VARCHAR(255),
    affiliations TEXT,

    -- Key details
    homeworld VARCHAR(255),
    birth_year VARCHAR(50),
    death_year VARCHAR(50),
    title VARCHAR(255),
    occupation TEXT,

    -- Physical attributes
    height VARCHAR(50),
    eye_color VARCHAR(100),
    skin_color VARCHAR(100),
    hair_color VARCHAR(100),

    -- Force sensitivity
    force_sensitive BOOLEAN DEFAULT FALSE,
    force_alignment VARCHAR(50),
    force_abilities TEXT,

    -- Skills and abilities
    skills TEXT,
    weapons TEXT,
    vehicles TEXT,

    -- Relationships
    master VARCHAR(255),
    apprentices TEXT,
    family TEXT,
    allies TEXT,
    enemies TEXT,

    -- Timeline
    era VARCHAR(255),
    first_appearance VARCHAR(255),
    notable_appearances TEXT,

    -- Status
    status VARCHAR(50),
    source_url VARCHAR(500),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

    UNIQUE KEY uk_lore_character_slug (lore_id, slug)
);

-- Indexes
CREATE INDEX idx_lore_characters_lore ON lore_characters (lore_id);
CREATE INDEX idx_lore_characters_species ON lore_characters (species);
CREATE INDEX idx_lore_characters_affiliation ON lore_characters (primary_affiliation);
CREATE INDEX idx_lore_characters_force ON lore_characters (force_sensitive);
CREATE INDEX idx_lore_characters_era ON lore_characters (era);
CREATE INDEX idx_lore_characters_status ON lore_characters (status);

-- Seed Star Wars characters
-- Get the Star Wars lore_id
SET @sw_lore_id = (SELECT id FROM game_lores WHERE slug = 'star-wars' LIMIT 1);

