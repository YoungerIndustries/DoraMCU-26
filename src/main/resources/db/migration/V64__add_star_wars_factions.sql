-- V64: Create lore_factions table and seed with Star Wars factions
-- This table stores detailed faction data for game lores, linked to game_lores via lore_id.

CREATE TABLE IF NOT EXISTS lore_factions (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,

    -- Link to game_lores
    lore_id BIGINT NOT NULL,
    FOREIGN KEY (lore_id) REFERENCES game_lores(id) ON DELETE CASCADE,

    -- Core identity
    name VARCHAR(255) NOT NULL,
    slug VARCHAR(255) NOT NULL,

    -- Description
    short_description VARCHAR(500),
    description TEXT,

    -- Classification
    allegiance VARCHAR(100),
    faction_type VARCHAR(100),

    -- Key details
    homeworld VARCHAR(255),
    headquarters VARCHAR(255),
    leaders TEXT,
    notable_members TEXT,

    -- Military and power
    military_strength VARCHAR(100),
    primary_weapons TEXT,
    symbols VARCHAR(255),

    -- Timeline
    era VARCHAR(255),
    founded_year VARCHAR(50),
    dissolved_year VARCHAR(50),
    active_status VARCHAR(50),

    -- Relationships
    allies TEXT,
    enemies TEXT,

    -- Source tracking
    source_url VARCHAR(500),

    -- Status
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

    UNIQUE KEY uk_lore_faction_slug (lore_id, slug)
);

-- Indexes
CREATE INDEX idx_lore_factions_lore ON lore_factions (lore_id);
CREATE INDEX idx_lore_factions_allegiance ON lore_factions (allegiance);
CREATE INDEX idx_lore_factions_type ON lore_factions (faction_type);
CREATE INDEX idx_lore_factions_era ON lore_factions (era);

-- Seed Star Wars factions
-- Get the Star Wars lore_id
